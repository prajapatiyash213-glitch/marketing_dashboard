import { parseDateCell } from "./dates.js";

/**
 * Parses individual URLs from a multi-line page visited string
 */
export function extractVisitedPages(pageVisitedStr) {
  if (!pageVisitedStr) return [];
  return String(pageVisitedStr)
    .split(/[\r\n;]+/)
    .map((p) => p.trim())
    .filter(Boolean);
}

/**
 * Enriches a raw drop-off lead record with parsed pages, clean journey paths, site ID, and parsed date
 */
export function formatDropoffRecord(r) {
  const pages = extractVisitedPages(r.pageVisited);
  const name = [r.firstName, r.lastName].filter(Boolean).join(" ").trim() || r.name || r.company || "Visitor";
  const lastPage = pages.length ? pages[pages.length - 1] : (r.pageVisited || "—");
  const firstPage = pages.length ? pages[0] : (r.pageVisited || "—");

  // Robust date parsing (DD-MM-YYYY, D/M/YYYY, etc.)
  const parsedDate = parseDateCell(r.leadDate || r.date, { dayFirst: true });

  // Detect site assignment from brand and pages visited
  let siteId = "unassigned";
  const brandNorm = String(r.brand || "").toLowerCase().trim();
  const pvNorm = String(r.pageVisited || "").toLowerCase();

  if (brandNorm.includes("acoe") || brandNorm.includes("automation") || pvNorm.includes("automationcoe.com")) {
    siteId = "automationcoe.com";
  } else if (brandNorm.includes("tecnoprism") || brandNorm.includes("techno") || pvNorm.includes("tecnoprism.com")) {
    siteId = "tecnoprism.com";
  }

  const hasConnect = Boolean(String(r.dateOfConnect || "").trim() || String(r.comments || "").trim());

  return {
    ...r,
    name,
    pages,
    pageCount: pages.length,
    firstPage,
    lastPage,
    parsedDate,
    siteId,
    hasConnect,
  };
}
